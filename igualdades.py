# Demonstração do funcionamento dos operadores relacionais

a = 13
b = 5

# Exibindo uma introdução
print("Operadores Relacionais (==, !=, <, >, <=, >=)")

# Considerando a = 13 e b = 5
print("Considerando a =", a, "e b =", b)

# Igualdade
print("a == b =", a == b)

# Diferença
print("a != b =", a != b)

# Menor que
print("a < b =", a < b)

# Maior que
print("a > b =", a > b)

# Menor ou igual a
print("a <= b =", a <= b)

# Maior ou igual a
print("a >= b =", a >= b)
